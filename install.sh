#!/usr/bin/env bash
# edit-tui 用户安装
#
# 自动识别 Linux / Termux：
#   Linux : 程序 -> ~/.local/share/edit    启动器 -> ~/.local/bin
#   Termux: 程序 -> ~/.local/share/edit    启动器 -> $PREFIX/bin（已在 PATH）
#
# 如果启动器目录不在 bash 的 PATH 里，会往 ~/.bashrc 追加一个带标记的块。
#
# 用法：
#   ./install.sh
#   ./install.sh --prefix DIR
#   ./install.sh --bin-dir DIR
#   ./install.sh --dry-run
#   ./install.sh --force

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ── 平台识别（必须在改任何变量之前读 Termux 的 $PREFIX） ─────
detect_platform() {
  if [ -n "${TERMUX_VERSION:-}" ]; then echo termux; return; fi
  case "${PREFIX:-}" in
    */com.termux/*) echo termux; return ;;
  esac
  if [ "$(uname -o 2>/dev/null || true)" = Android ]; then echo termux; return; fi
  if [ "$(uname -s 2>/dev/null || true)" = Linux ]; then echo linux; return; fi
  echo unix
}

PLATFORM="$(detect_platform)"
TERMUX_HOST_PREFIX="${PREFIX:-}"

if [ "$PLATFORM" = termux ] && [ -n "$TERMUX_HOST_PREFIX" ]; then
  DEFAULT_BIN="${TERMUX_HOST_PREFIX%/}/bin"
else
  DEFAULT_BIN="${XDG_BIN_HOME:-$HOME/.local/bin}"
fi

BIN_DIR="$DEFAULT_BIN"
INSTALL_DIR="${EDIT_HOME:-$HOME/.local/share/edit}"
RC="${EDIT_BASHRC:-$HOME/.bashrc}"
DRY_RUN=0
FORCE=0

usage() {
  cat <<'EOF'
用法: ./install.sh [选项]

  --prefix DIR     程序目录（默认 ~/.local/share/edit）
  --bin-dir DIR    启动器目录（默认 Linux: ~/.local/bin，Termux: $PREFIX/bin）
  --dry-run        只打印将要执行的操作
  --force          覆盖非本脚本创建的安装目录 / 同名启动器
  -h, --help       显示本帮助
EOF
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --prefix)   INSTALL_DIR="$2"; shift ;;
    --bin-dir)  BIN_DIR="$2"; shift ;;
    --dry-run)  DRY_RUN=1 ;;
    --force)    FORCE=1 ;;
    -h|--help)  usage 0 ;;
    *) echo "未知参数: $1" >&2; usage 1 ;;
  esac
  shift
done
LAUNCHER="$BIN_DIR/edit-tui"

say() { printf '%s\n' "$*"; }
run() {
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    echo
  else
    "$@"
  fi
}

# ── 基础环境 ─────────────────────────────────────────────────
case "$PLATFORM" in
  termux) say "检测到 Termux（$TERMUX_HOST_PREFIX）" ;;
  linux)  say "检测到 Linux" ;;
  *)      say "检测到 Unix-like 系统" ;;
esac

if ! command -v racket >/dev/null; then
  case "$PLATFORM" in
    termux) echo "找不到 racket；Termux 下先执行: pkg install racket" >&2 ;;
    *)      echo "找不到 racket；请先安装 Racket" >&2 ;;
  esac
  exit 1
fi
command -v raco >/dev/null || { echo "找不到 raco" >&2; exit 1; }
command -v tar  >/dev/null || { echo "找不到 tar" >&2; exit 1; }

missing=""
racket -e '(require tui)'          >/dev/null 2>&1 || missing="$missing tui"
racket -e '(require html-parsing)' >/dev/null 2>&1 || missing="$missing html-parsing"
if [ -n "$missing" ]; then
  {
    echo "缺少运行时依赖:$missing"
    echo "先安装一次（Linux / Termux 相同）："
    echo "  raco pkg install racket-tui html-parsing"
  } >&2
  exit 1
fi

if ! command -v man >/dev/null; then
  case "$PLATFORM" in
    termux) say "提示: 没有 man；C 文档使用内置索引，需要手册页可: pkg install man" ;;
    *)      say "提示: 没有 man；C 文档使用内置索引，需要手册页可安装 man-db / manpages-dev" ;;
  esac
fi

# ── 复制 + 编译 ──────────────────────────────────────────────
JOBS=4
if command -v nproc >/dev/null; then
  JOBS="$(nproc)"
elif command -v getconf >/dev/null; then
  JOBS="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"
fi

if [ "$DRY_RUN" = 1 ]; then
  say "[dry-run] 复制 core/ edit-tui/ 到 $INSTALL_DIR"
  say "[dry-run] raco make -j $JOBS $INSTALL_DIR/edit-tui/edit.rkt"
else
  if [ -e "$INSTALL_DIR" ] || [ -L "$INSTALL_DIR" ]; then
    if grep -q '^EDIT_INSTALL=' "$INSTALL_DIR/.edit-install" 2>/dev/null; then
      say "替换已有安装: $INSTALL_DIR"
      rm -rf "$INSTALL_DIR"
    elif [ "$FORCE" = 1 ]; then
      say "--force 覆盖: $INSTALL_DIR"
      rm -rf "$INSTALL_DIR"
    else
      echo "$INSTALL_DIR 已存在且不是本脚本的安装；用 --force 覆盖" >&2
      exit 1
    fi
  fi

  stage="$(mktemp -d)"
  trap 'rm -rf "$stage"' EXIT
  tar -C "$REPO" -cf - --exclude=compiled --exclude='edit-tui/test' core edit-tui \
    | tar -C "$stage" -xf -
  raco make -j "$JOBS" "$stage/edit-tui/edit.rkt"

  mkdir -p "$(dirname "$INSTALL_DIR")"
  mv "$stage" "$INSTALL_DIR"
  stage=""
  trap - EXIT
  printf 'EDIT_INSTALL=4\nPLATFORM=%s\nSOURCE=%s\n' "$PLATFORM" "$REPO" \
    > "$INSTALL_DIR/.edit-install"
fi

# ── 启动器 ───────────────────────────────────────────────────
if [ -e "$LAUNCHER" ] || [ -L "$LAUNCHER" ]; then
  if ! head -n 3 "$LAUNCHER" 2>/dev/null | grep -qF '# generated by edit-tui install.sh'; then
    if [ "$FORCE" != 1 ]; then
      echo "已存在非本脚本生成的 $LAUNCHER；用 --force 覆盖" >&2
      exit 1
    fi
  fi
fi

say "写启动器: $LAUNCHER"
if [ "$DRY_RUN" != 1 ]; then
  mkdir -p "$BIN_DIR"
  tmp="$(mktemp)"
  cat > "$tmp" <<EOF
#!/bin/sh
# generated by edit-tui install.sh
exec "$(command -v racket)" "$INSTALL_DIR/edit-tui/edit.rkt" "\$@"
EOF
  chmod 755 "$tmp"
  install -m 755 "$tmp" "$LAUNCHER" 2>/dev/null || { cp "$tmp" "$LAUNCHER"; chmod 755 "$LAUNCHER"; }
  rm -f "$tmp"
fi

# ── bash 环境 ────────────────────────────────────────────────
path_has_dir() {
  case ":$PATH:" in
    *":$1:"*) return 0 ;;
    *)        return 1 ;;
  esac
}

RC_CHANGED=0
if path_has_dir "$BIN_DIR"; then
  say "$BIN_DIR 已在 PATH 中，不修改 $RC"
elif grep -qF "$BIN_DIR" "$RC" 2>/dev/null; then
  say "$RC 已包含 $BIN_DIR，不修改"
elif [ "$DRY_RUN" = 1 ]; then
  say "[dry-run] 把 $BIN_DIR 追加到 $RC"
else
  say "把 $BIN_DIR 追加到 $RC"
  touch "$RC"
  cat >> "$RC" <<EOF

# >>> edit-tui >>>
case ":\$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) export PATH="$BIN_DIR:\$PATH" ;;
esac
# <<< edit-tui <<<
EOF
  RC_CHANGED=1
fi

say ""
say "完成。运行: edit-tui"
if [ "$DRY_RUN" = 1 ]; then
  say "（dry-run，未做任何修改）"
elif [ "$RC_CHANGED" = 1 ]; then
  say "如果当前终端里还找不到命令，执行: source $RC"
fi
