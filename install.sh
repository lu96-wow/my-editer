#!/usr/bin/env bash
# edit-tui 用户安装
#
# 安装位置（全部在用户目录，不需要 sudo）：
#   ~/.local/share/edit      程序 + 编译结果
#   ~/.local/bin/edit-tui    启动器
#   ~/.bashrc                确保 ~/.local/bin 在 PATH（带标记块，可撤销）
#
# 用法：
#   ./install.sh
#   ./install.sh --prefix DIR
#   ./install.sh --bin-dir DIR
#   ./install.sh --dry-run
#   ./install.sh --force

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
PREFIX="${EDIT_PREFIX:-$HOME/.local/share/edit}"
RC="${EDIT_BASHRC:-$HOME/.bashrc}"
LAUNCHER="$BIN_DIR/edit-tui"
MARK='# generated by edit-tui install.sh'
DRY_RUN=0
FORCE=0

usage() {
  cat <<'EOF'
用法: ./install.sh [选项]

  --prefix DIR     程序目录（默认 ~/.local/share/edit）
  --bin-dir DIR    启动器目录（默认 ~/.local/bin）
  --dry-run        只打印将要执行的操作
  --force          覆盖非本脚本创建的安装目录 / 同名启动器
  -h, --help       显示本帮助
EOF
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --prefix)   PREFIX="$2"; shift ;;
    --bin-dir)  BIN_DIR="$2"; shift ;;
    --dry-run)  DRY_RUN=1 ;;
    --force)    FORCE=1 ;;
    -h|--help)  usage 0 ;;
    *) echo "未知参数: $1" >&2; usage 1 ;;
  esac
  shift
done
LAUNCHER="$BIN_DIR/edit-tui"

say() { printf '%s\n' "$*"; }
run() {
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    echo
  else
    "$@"
  fi
}

command -v racket >/dev/null || { echo "找不到 racket" >&2; exit 1; }
command -v raco   >/dev/null || { echo "找不到 raco" >&2; exit 1; }

# ── 依赖检查（只提示，不安装） ───────────────────────────────
missing=""
racket -e '(require tui)'          >/dev/null 2>&1 || missing="$missing tui"
racket -e '(require html-parsing)' >/dev/null 2>&1 || missing="$missing html-parsing"
if [ -n "$missing" ]; then
  {
    echo "缺少运行时依赖:$missing"
    echo "先安装一次："
    echo "  raco pkg install racket-tui html-parsing"
  } >&2
  exit 1
fi

# ── 复制 + 编译 ──────────────────────────────────────────────
JOBS=4
if command -v nproc >/dev/null; then JOBS="$(nproc)"; fi

if [ "$DRY_RUN" = 1 ]; then
  say "[dry-run] 复制 core/ edit-tui/ 到 $PREFIX"
  say "[dry-run] raco make -j $JOBS $PREFIX/edit-tui/edit.rkt"
else
  if [ -e "$PREFIX" ] || [ -L "$PREFIX" ]; then
    if grep -q '^EDIT_INSTALL=' "$PREFIX/.edit-install" 2>/dev/null; then
      say "替换已有安装: $PREFIX"
      rm -rf "$PREFIX"
    elif [ "$FORCE" = 1 ]; then
      say "--force 覆盖: $PREFIX"
      rm -rf "$PREFIX"
    else
      echo "$PREFIX 已存在且不是本脚本的安装；用 --force 覆盖" >&2
      exit 1
    fi
  fi

  stage="$(mktemp -d)"
  trap 'rm -rf "$stage"' EXIT
  tar -C "$REPO" -cf - --exclude=compiled --exclude='edit-tui/test' core edit-tui \
    | tar -C "$stage" -xf -
  raco make -j "$JOBS" "$stage/edit-tui/edit.rkt"

  mkdir -p "$(dirname "$PREFIX")"
  mv "$stage" "$PREFIX"
  stage=""
  trap - EXIT
  printf 'EDIT_INSTALL=3\nSOURCE=%s\n' "$REPO" > "$PREFIX/.edit-install"
fi

# ── 启动器 ───────────────────────────────────────────────────
if [ -e "$LAUNCHER" ] || [ -L "$LAUNCHER" ]; then
  if ! head -n 3 "$LAUNCHER" 2>/dev/null | grep -qF "$MARK"; then
    if [ "$FORCE" != 1 ]; then
      echo "已存在非本脚本生成的 $LAUNCHER；用 --force 覆盖" >&2
      exit 1
    fi
  fi
fi

say "写启动器: $LAUNCHER"
if [ "$DRY_RUN" != 1 ]; then
  mkdir -p "$BIN_DIR"
  tmp="$(mktemp)"
  cat > "$tmp" <<EOF
#!/bin/sh
$MARK
exec "$(command -v racket)" "$PREFIX/edit-tui/edit.rkt" "\$@"
EOF
  chmod 755 "$tmp"
  install -m 755 "$tmp" "$LAUNCHER" 2>/dev/null || { cp "$tmp" "$LAUNCHER"; chmod 755 "$LAUNCHER"; }
  rm -f "$tmp"
fi

# ── bash 环境：确保 BIN_DIR 在 PATH ──────────────────────────
if grep -qF "$BIN_DIR" "$RC" 2>/dev/null; then
  say "$RC 已包含 $BIN_DIR，不修改"
elif [ "$DRY_RUN" = 1 ]; then
  say "[dry-run] 把 $BIN_DIR 追加到 $RC"
else
  say "把 $BIN_DIR 追加到 $RC"
  touch "$RC"
  cat >> "$RC" <<EOF

# >>> edit-tui >>>
case ":\$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) export PATH="$BIN_DIR:\$PATH" ;;
esac
# <<< edit-tui <<<
EOF
fi

say ""
say "完成。新开终端或执行: source $RC"
say "然后运行: edit-tui"
if [ "$DRY_RUN" = 1 ]; then
  say "（dry-run，未做任何修改）"
fi
