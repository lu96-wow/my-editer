#!/usr/bin/env bash
# edit-tui 用户卸载
#
# 删除：~/.local/share/edit、~/.local/bin/edit-tui、install.sh 写入的 PATH 块。
# 不删除任何 workspace/.editdata。
#
# 用法：
#   ./uninstall.sh
#   ./uninstall.sh --prefix DIR
#   ./uninstall.sh --bin-dir DIR
#   ./uninstall.sh --dry-run

set -euo pipefail

BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
PREFIX="${EDIT_PREFIX:-$HOME/.local/share/edit}"
RC="${EDIT_BASHRC:-$HOME/.bashrc}"
LAUNCHER="$BIN_DIR/edit-tui"
DRY_RUN=0

usage() {
  cat <<'EOF'
用法: ./uninstall.sh [选项]

  --prefix DIR     程序目录（默认 ~/.local/share/edit）
  --bin-dir DIR    启动器目录（默认 ~/.local/bin）
  --dry-run        只打印将要执行的操作
  -h, --help       显示本帮助
EOF
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --prefix)   PREFIX="$2"; shift ;;
    --bin-dir)  BIN_DIR="$2"; shift ;;
    --dry-run)  DRY_RUN=1 ;;
    -h|--help)  usage 0 ;;
    *) echo "未知参数: $1" >&2; usage 1 ;;
  esac
  shift
done
LAUNCHER="$BIN_DIR/edit-tui"

say() { printf '%s\n' "$*"; }
run() {
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    echo
  else
    "$@"
  fi
}

if [ -e "$LAUNCHER" ] || [ -L "$LAUNCHER" ]; then
  if head -n 3 "$LAUNCHER" 2>/dev/null | grep -qF '# generated by edit-tui install.sh'; then
    say "删除启动器: $LAUNCHER"
    run rm -f "$LAUNCHER"
  else
    say "跳过非本脚本生成的 $LAUNCHER"
  fi
fi

if [ -e "$PREFIX" ] || [ -L "$PREFIX" ]; then
  if grep -q '^EDIT_INSTALL=' "$PREFIX/.edit-install" 2>/dev/null; then
    say "删除程序目录: $PREFIX"
    run rm -rf "$PREFIX"
  else
    say "跳过：$PREFIX 没有安装标记"
  fi
fi

if [ -f "$RC" ] && grep -qF '# >>> edit-tui >>>' "$RC"; then
  say "从 $RC 移除 PATH 块"
  if [ "$DRY_RUN" != 1 ]; then
    tmp="$(mktemp)"
    awk '
      $0 == "# >>> edit-tui >>>" { skip = 1; next }
      $0 == "# <<< edit-tui <<<" { skip = 0; next }
      !skip
    ' "$RC" > "$tmp"
    cat "$tmp" > "$RC"
    rm -f "$tmp"
  fi
fi

say "卸载完成。新开终端后生效。"
