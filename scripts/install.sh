#!/usr/bin/env bash
# edit-tui 安装脚本（不使用 Racket 包管理）
#
# 两种方式：
#   --link  直接用源码树：在仓库里 raco make，启动器指向仓库入口（开发用）
#   --copy  复制 core/ + edit-tui/ 到安装目录，在目标目录编译（稳定安装）
#
# 不再执行 raco pkg install / raco setup，因此不会注册 collection，
# 也不受其它失效 package link 影响。tui / html-parsing 作为外部依赖
# 仍然需要已安装（脚本会检查并提示）。
#
# 默认启动器装到 /usr/local/bin（需要 sudo）；sudo 运行时通过
# $SUDO_USER 降权执行编译，避免 root 的 user scope 影响模块解析。
#
# 用法：
#   sudo scripts/install.sh              # copy 到 /usr/local/lib/edit
#   sudo scripts/install.sh --link       # 启动器指向当前仓库
#   scripts/install.sh --user            # copy 到 ~/.local/share/edit
#   scripts/install.sh --user --link     # 用户目录启动器 + 源码树
#   scripts/install.sh --prefix DIR      # 自定义 copy 目标
#   scripts/install.sh --bin-dir DIR
#   scripts/install.sh --dry-run

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SELF="$REPO/scripts/install.sh"
ORIG_ARGS=("$@")

LAUNCHER_NAME=edit-tui
MARKER='# generated by edit-tui install.sh'
PREFIX_MARKER='.edit-install'

usage() {
  cat <<'EOF'
用法: scripts/install.sh [选项]

  --link           使用源码树（默认）：raco make + 启动器指向仓库
  --copy           复制到安装目录并在那里编译（稳定安装）
  --user           用户模式：bin 到 ~/.local/bin，copy 前缀到 ~/.local/share/edit
  --prefix DIR     copy 模式的安装目录（默认 /usr/local/lib/edit）
  --bin-dir DIR    启动器目录（默认 /usr/local/bin）
  --no-rc          bin 目录不在 PATH 时也不改 shell rc
  --force          覆盖非本脚本创建的安装目录 / 同名文件
  --dry-run        只打印将要执行的操作
  -h, --help       显示本帮助
EOF
  exit "${1:-0}"
}

# ── 运行身份 ─────────────────────────────────────────────────
if [ "${EUID:-$(id -u)}" -eq 0 ] && [ -n "${SUDO_USER:-}" ] && [ "$SUDO_USER" != root ]; then
  RUN_USER="$SUDO_USER"
  RUN_HOME="$(getent passwd "$RUN_USER" | cut -d: -f6 || true)"
  RUN_SHELL="$(getent passwd "$RUN_USER" | cut -d: -f7 || true)"
  IS_SUDO=1
else
  RUN_USER="$(id -un)"
  RUN_HOME="$HOME"
  RUN_SHELL="${SHELL:-/bin/bash}"
  IS_SUDO=0
fi
[ -n "${RUN_HOME:-}" ] || { echo "无法确定 $RUN_USER 的 home 目录" >&2; exit 1; }
[ -n "${RUN_SHELL:-}" ] || RUN_SHELL=/bin/bash

if [ "$IS_SUDO" = 1 ]; then
  STATE_BASE="$RUN_HOME/.local/state"
  CONFIG_BASE="$RUN_HOME/.config"
  CACHE_BASE="$RUN_HOME/.cache"
  DATA_BASE="$RUN_HOME/.local/share"
else
  STATE_BASE="${XDG_STATE_HOME:-$HOME/.local/state}"
  CONFIG_BASE="${XDG_CONFIG_HOME:-$HOME/.config}"
  CACHE_BASE="${XDG_CACHE_HOME:-$HOME/.cache}"
  DATA_BASE="${XDG_DATA_HOME:-$HOME/.local/share}"
fi
MANIFEST="$STATE_BASE/edit/install.conf"

MODE=copy
BIN_DIR=/usr/local/bin
BIN_DIR_SET=0
PREFIX=""
PREFIX_SET=0
USER_MODE=0
NO_RC=0
DRY_RUN=0
FORCE=0

while [ $# -gt 0 ]; do
  case "$1" in
    --link)      MODE=link ;;
    --copy)      MODE=copy ;;
    --user)      USER_MODE=1 ;;
    --prefix)    PREFIX="$2"; PREFIX_SET=1; shift ;;
    --bin-dir)   BIN_DIR="$2"; BIN_DIR_SET=1; shift ;;
    --no-rc)     NO_RC=1 ;;
    --dry-run)   DRY_RUN=1 ;;
    --force)     FORCE=1 ;;
    -h|--help)   usage 0 ;;
    *) echo "未知参数: $1" >&2; usage 1 ;;
  esac
  shift
done

if [ "$USER_MODE" = 1 ] && [ "$BIN_DIR_SET" = 0 ]; then
  BIN_DIR="$RUN_HOME/.local/bin"
fi

if [ "$MODE" = link ]; then
  PREFIX="$REPO"
elif [ "$PREFIX_SET" = 0 ]; then
  if [ "$USER_MODE" = 1 ]; then
    PREFIX="$DATA_BASE/edit"
  else
    PREFIX=/usr/local/lib/edit
  fi
fi
LAUNCHER="$BIN_DIR/$LAUNCHER_NAME"

say() { printf '%s\n' "$*"; }
run() {
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    echo
  else
    "$@"
  fi
}

as_user() {
  if [ "$IS_SUDO" = 1 ]; then
    sudo -H -u "$RUN_USER" -- "$@"
  else
    "$@"
  fi
}

need_sudo() {
  {
    echo "无法写入 $1（当前用户: $RUN_USER）。"
    echo
    echo "请用 sudo 重新运行："
    printf '  sudo %q' "$SELF"
    if [ "${#ORIG_ARGS[@]}" -gt 0 ]; then printf ' %q' "${ORIG_ARGS[@]}"; fi
    echo
    echo
    echo "或者使用用户模式（不需要 sudo）："
    printf '  %q --user\n' "$SELF"
  } >&2
  exit 1
}

# ── 0. 权限检查（先检查，避免装一半） ────────────────────────
if [ ! -d "$BIN_DIR" ]; then
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] 需要创建目录 $BIN_DIR"
  elif [ "$IS_SUDO" = 1 ] || [ -w "$(dirname "$BIN_DIR")" ]; then
    mkdir -p "$BIN_DIR"
  else
    need_sudo "$BIN_DIR"
  fi
fi
if [ ! -w "$BIN_DIR" ] && [ "$DRY_RUN" != 1 ]; then
  need_sudo "$BIN_DIR"
fi

if [ "$MODE" = copy ]; then
  parent="$(dirname "$PREFIX")"
  if [ ! -d "$parent" ]; then
    if [ "$DRY_RUN" = 1 ]; then
      say "[dry-run] 需要创建目录 $parent"
    elif [ "$IS_SUDO" = 1 ] || [ -w "$(dirname "$parent")" ]; then
      mkdir -p "$parent"
    else
      need_sudo "$PREFIX"
    fi
  fi
  if [ ! -w "$parent" ] && [ ! -w "$PREFIX" ] && [ "$DRY_RUN" != 1 ]; then
    need_sudo "$PREFIX"
  fi
fi

# ── 1. 定位真实用户的 racket / raco ──────────────────────────
RACKET_BIN="$(as_user sh -c 'command -v racket' 2>/dev/null || true)"
RACO_BIN="$(as_user sh -c 'command -v raco' 2>/dev/null || true)"
[ -n "$RACKET_BIN" ] || { echo "找不到用户 $RUN_USER 的 racket" >&2; exit 1; }
[ -n "$RACO_BIN" ]   || { echo "找不到用户 $RUN_USER 的 raco" >&2; exit 1; }

# ── 2. 外部依赖检查（不是本编辑器，不被本脚本安装） ─────────
missing=""
as_user "$RACKET_BIN" -e '(require tui)'          >/dev/null 2>&1 || missing="$missing tui"
as_user "$RACKET_BIN" -e '(require html-parsing)' >/dev/null 2>&1 || missing="$missing html-parsing"
if [ -n "$missing" ]; then
  {
    echo "缺少运行时依赖:$missing"
    echo "先安装一次（与本编辑器的安装方式无关）："
    echo "  raco pkg install racket-tui html-parsing"
  } >&2
  exit 1
fi

RACKET_VERSION="$(as_user "$RACKET_BIN" -e '(displayln (version))' 2>/dev/null || echo unknown)"

# ── 3. 旧包提示 ──────────────────────────────────────────────
legacy_dir="$(as_user "$RACO_BIN" pkg show --dir edit 2>/dev/null \
              | awk '$1 == "edit" { print $NF }' || true)"
if [ -n "$legacy_dir" ]; then
  say "提示：检测到旧的 Racket 包 edit（$legacy_dir）；本安装不再使用它。"
  say "      需要清理时执行: raco pkg remove --no-setup edit"
fi

# ── 4. 准备并编译 ────────────────────────────────────────────
JOBS=4
if command -v nproc >/dev/null; then JOBS="$(nproc)"; fi

if [ "$MODE" = link ]; then
  say "源码安装（link）: $PREFIX"
  if [ "$DRY_RUN" = 1 ]; then
    say "[dry-run] 将在 $PREFIX 中执行 raco make -j $JOBS $PREFIX/edit-tui/edit.rkt"
  else
    as_user "$RACO_BIN" make -j "$JOBS" "$PREFIX/edit-tui/edit.rkt"
  fi
else
  say "复制安装（copy）: $PREFIX"
  if [ "$DRY_RUN" = 1 ]; then
    stage="/tmp/edit-tui-stage.dry-run"
    say "[dry-run] 复制 core/ edit-tui/ 到 $stage"
    say "[dry-run] raco make -j $JOBS $stage/edit-tui/edit.rkt"
    say "[dry-run] 安装 $stage -> $PREFIX"
  else
    stage="$(as_user mktemp -d)"
    trap 'rm -rf "$stage"' EXIT
    as_user sh -c 'cd "$1" && tar -cf - --exclude=compiled --exclude="edit-tui/test" core edit-tui | tar -xf - -C "$2"' \
      sh "$REPO" "$stage"
    as_user "$RACO_BIN" make -j "$JOBS" "$stage/edit-tui/edit.rkt"

    if [ -e "$PREFIX" ] || [ -L "$PREFIX" ]; then
      if [ -f "$PREFIX/$PREFIX_MARKER" ] && grep -q '^EDIT_INSTALL=' "$PREFIX/$PREFIX_MARKER"; then
        say "替换已有安装: $PREFIX"
        if [ "$IS_SUDO" = 1 ] && [ "$USER_MODE" = 1 ]; then as_user rm -rf "$PREFIX"; else rm -rf "$PREFIX"; fi
      elif [ "$FORCE" = 1 ]; then
        say "--force 覆盖: $PREFIX"
        if [ "$IS_SUDO" = 1 ] && [ "$USER_MODE" = 1 ]; then as_user rm -rf "$PREFIX"; else rm -rf "$PREFIX"; fi
      else
        echo "$PREFIX 已存在且不是本脚本的安装；用 --force 覆盖" >&2
        exit 1
      fi
    fi

    if [ "$IS_SUDO" = 1 ] && [ "$USER_MODE" = 0 ]; then
      cp -a "$stage" "$PREFIX"
      chown -R root:root "$PREFIX"
    else
      if [ "$IS_SUDO" = 1 ]; then as_user mv "$stage" "$PREFIX"; else mv "$stage" "$PREFIX"; fi
      stage=""
      trap - EXIT
    fi
    if [ "$IS_SUDO" = 1 ] && [ "$USER_MODE" = 1 ]; then
      as_user sh -c 'cat > "$1"' sh "$PREFIX/$PREFIX_MARKER" <<EOF
EDIT_INSTALL=2
KIND=copy
SOURCE=$REPO
EOF
    else
      cat > "$PREFIX/$PREFIX_MARKER" <<EOF
EDIT_INSTALL=2
KIND=copy
SOURCE=$REPO
EOF
    fi
  fi
fi

# ── 5. wrapper ───────────────────────────────────────────────
if [ -e "$LAUNCHER" ] || [ -L "$LAUNCHER" ]; then
  if ! head -n 3 "$LAUNCHER" 2>/dev/null | grep -qF "$MARKER"; then
    if [ "$FORCE" != 1 ]; then
      echo "已存在非本脚本生成的 $LAUNCHER；用 --force 覆盖" >&2
      exit 1
    fi
  fi
fi

say "写 wrapper: $LAUNCHER"
if [ "$DRY_RUN" != 1 ]; then
  tmp="$(mktemp)"
  cat > "$tmp" <<EOF
#!/bin/sh
$MARKER
# 修改请重跑 scripts/install.sh；卸载用 scripts/uninstall.sh
exec "$RACKET_BIN" "$PREFIX/edit-tui/edit.rkt" "\$@"
EOF
  chmod 755 "$tmp"
  if [ "$IS_SUDO" = 1 ] && [ "$USER_MODE" = 1 ]; then
    as_user mkdir -p "$BIN_DIR"
    as_user install -m 755 "$tmp" "$LAUNCHER"
  else
    install -m 755 "$tmp" "$LAUNCHER" 2>/dev/null || { cp "$tmp" "$LAUNCHER"; chmod 755 "$LAUNCHER"; }
  fi
  rm -f "$tmp"
fi

# ── 6. PATH ──────────────────────────────────────────────────
path_has_dir() {
  case ":$PATH:" in
    *":$1:"*) return 0 ;;
    *)        return 1 ;;
  esac
}

case "$BIN_DIR" in
  /usr/local/bin|/usr/bin|/bin)
    RC_FILE=""; RC_BLOCK=0
    say "$BIN_DIR 是标准 PATH 目录，不修改 shell 配置"
    ;;
  *)
    case "$RUN_SHELL" in
      */fish) RC_FILE="$RUN_HOME/.config/fish/config.fish" ;;
      */zsh)  RC_FILE="$RUN_HOME/.zshrc" ;;
      *)      RC_FILE="$RUN_HOME/.bashrc" ;;
    esac
    RC_BLOCK=0
    if path_has_dir "$BIN_DIR"; then
      say "$BIN_DIR 已在 PATH 中，不修改 shell 配置"
    elif [ "$NO_RC" = 1 ]; then
      say "提示：$BIN_DIR 不在 PATH；按要求未修改 shell 配置"
    elif grep -qF "$BIN_DIR" "$RC_FILE" 2>/dev/null; then
      say "$RC_FILE 已引用 $BIN_DIR，不重复追加"
    else
      say "把 $BIN_DIR 追加到 $RC_FILE（带标记，卸载可移除）"
      if [ "$DRY_RUN" != 1 ]; then
        as_user mkdir -p "$(dirname "$RC_FILE")"
        case "$RC_FILE" in
          */config.fish)
            as_user sh -c 'cat >> "$1"' sh "$RC_FILE" <<EOF

# >>> edit-tui >>>
if not contains "$BIN_DIR" \$PATH
    set -gx PATH "$BIN_DIR" \$PATH
end
# <<< edit-tui <<<
EOF
            ;;
          *)
            as_user sh -c 'cat >> "$1"' sh "$RC_FILE" <<EOF

# >>> edit-tui >>>
case ":\$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) PATH="$BIN_DIR:\$PATH" ;;
esac
export PATH
# <<< edit-tui <<<
EOF
            ;;
        esac
        RC_BLOCK=1
        say "已写入；新开终端或 source $RC_FILE 后生效"
      fi
    fi
    ;;
esac

# ── 7. manifest ──────────────────────────────────────────────
say "写安装记录: $MANIFEST"
if [ "$DRY_RUN" != 1 ]; then
  tmp="$(mktemp)"
  {
    printf 'FORMAT=%q\n' 2
    printf 'KIND=%q\n' "$MODE"
    printf 'SOURCE=%q\n' "$REPO"
    printf 'PREFIX=%q\n' "$PREFIX"
    printf 'PREFIX_OWNED=%q\n' "$([ "$MODE" = copy ] && echo 1 || echo 0)"
    printf 'BIN_DIR=%q\n' "$BIN_DIR"
    printf 'LAUNCHER=%q\n' "$LAUNCHER"
    printf 'RACKET=%q\n' "$RACKET_BIN"
    printf 'RACKET_VERSION=%q\n' "$RACKET_VERSION"
    printf 'RUN_USER=%q\n' "$RUN_USER"
    printf 'RUN_HOME=%q\n' "$RUN_HOME"
    printf 'RC_FILE=%q\n' "$RC_FILE"
    printf 'RC_BLOCK=%q\n' "$RC_BLOCK"
    printf 'CONFIG_BASE=%q\n' "$CONFIG_BASE"
    printf 'STATE_BASE=%q\n' "$STATE_BASE"
    printf 'CACHE_BASE=%q\n' "$CACHE_BASE"
    printf 'DATA_BASE=%q\n' "$DATA_BASE"
  } > "$tmp"
  as_user mkdir -p "$(dirname "$MANIFEST")"
  as_user sh -c 'cat > "$1"' sh "$MANIFEST" < "$tmp"
  rm -f "$tmp"
fi

say ""
say "完成。运行: $LAUNCHER_NAME"
if [ "$DRY_RUN" = 1 ]; then
  say "（dry-run，未做任何修改）"
fi
