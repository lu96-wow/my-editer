#!/usr/bin/env bash
# edit-tui 安装脚本
#
# 做的事：
#   1. 把仓库装成 Racket 包（默认 --link，改源码立即生效）
#   2. raco setup 编译 core / edit-tui
#   3. 在 $XDG_BIN_HOME（默认 ~/.local/bin）生成稳定 wrapper：edit-tui
#   4. 仅当该目录不在 PATH 时，才往 shell rc 追加带标记的 PATH 块
#   5. 记录 install.conf，供 uninstall.sh 精确回滚
#
# 用法：
#   scripts/install.sh                 # 开发安装（link）
#   scripts/install.sh --copy          # 复制进包目录，不依赖源码树
#   scripts/install.sh --bin-dir DIR   # 指定 wrapper 目录
#   scripts/install.sh --no-rc         # 不修改 shell rc
#   scripts/install.sh --dry-run
#   scripts/install.sh --force         # 覆盖非本脚本生成的同名文件

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODE=link
BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/edit"
MANIFEST="$STATE_DIR/install.conf"
NO_RC=0
DRY_RUN=0
FORCE=0
PKG=edit
LAUNCHER_NAME=edit-tui

usage() {
  sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --link)      MODE=link ;;
    --copy)      MODE=copy ;;
    --bin-dir)   BIN_DIR="$2"; shift ;;
    --no-rc)     NO_RC=1 ;;
    --dry-run)   DRY_RUN=1 ;;
    --force)     FORCE=1 ;;
    -h|--help)   usage 0 ;;
    *) echo "未知参数: $1" >&2; usage 1 ;;
  esac
  shift
done

LAUNCHER="$BIN_DIR/$LAUNCHER_NAME"
MARKER='# generated by edit-tui install.sh'

say()  { printf '%s\n' "$*"; }
run()  {
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    echo
  else
    "$@"
  fi
}

command -v racket >/dev/null || { echo "找不到 racket" >&2; exit 1; }
command -v raco   >/dev/null || { echo "找不到 raco" >&2; exit 1; }

RACKET_BIN="$(command -v racket)"

pkg_installed() {
  raco pkg show --dir "$PKG" 2>/dev/null \
    | awk -v p="$PKG" '$1 == p { found = 1 } END { exit !found }'
}

# ── 1. 安装包 ────────────────────────────────────────────────
if pkg_installed; then
  say "包 $PKG 已安装，跳过 raco pkg install（切换 --link/--copy 请先跑 uninstall.sh）"
else
  say "安装 $PKG（$MODE）..."
  if [ "$MODE" = link ]; then
    run raco pkg install --link --auto --no-setup "$REPO"
  else
    run raco pkg install --copy --auto --no-setup "$REPO"
  fi
fi

# ── 2. 编译 ──────────────────────────────────────────────────
JOBS=4
if command -v nproc >/dev/null; then JOBS="$(nproc)"; fi
say "raco setup -l core edit-tui"
say "  （如果这里失败，先看 raco pkg show -u 有没有指向不存在目录的失效 link）"
run raco setup -D -j "$JOBS" -l core edit-tui

# ── 3. wrapper ───────────────────────────────────────────────
if [ -e "$LAUNCHER" ] || [ -L "$LAUNCHER" ]; then
  if ! head -n 3 "$LAUNCHER" 2>/dev/null | grep -qF "$MARKER"; then
    if [ "$FORCE" != 1 ]; then
      echo "已存在非本脚本生成的 $LAUNCHER；用 --force 覆盖" >&2
      exit 1
    fi
  fi
fi

say "写 wrapper: $LAUNCHER"
run mkdir -p "$BIN_DIR"
if [ "$DRY_RUN" != 1 ]; then
  tmp="$LAUNCHER.tmp.$$"
  cat > "$tmp" <<EOF
#!/bin/sh
$MARKER
# 修改请重跑 scripts/install.sh；卸载用 scripts/uninstall.sh
exec "$RACKET_BIN" -l edit-tui/edit "\$@"
EOF
  chmod 755 "$tmp"
  mv -f "$tmp" "$LAUNCHER"
fi

# ── 4. PATH ──────────────────────────────────────────────────
path_has_dir() {
  case ":$PATH:" in
    *":$1:"*) return 0 ;;
    *)        return 1 ;;
  esac
}

RC_FILE=""
RC_BLOCK=0
case ":${SHELL:-}" in
  */fish) RC_FILE="$HOME/.config/fish/config.fish" ;;
  */zsh)  RC_FILE="$HOME/.zshrc" ;;
  *)      RC_FILE="$HOME/.bashrc" ;;
esac

if path_has_dir "$BIN_DIR"; then
  say "$BIN_DIR 已在 PATH 中，不修改 shell 配置"
elif [ "$NO_RC" = 1 ]; then
  say "提示：$BIN_DIR 不在 PATH；按要求未修改 shell 配置"
elif grep -qF "$BIN_DIR" "$RC_FILE" 2>/dev/null; then
  say "$RC_FILE 已引用 $BIN_DIR，不重复追加"
else
  say "把 $BIN_DIR 追加到 $RC_FILE（带标记，卸载可移除）"
  if [ "$DRY_RUN" != 1 ]; then
    mkdir -p "$(dirname "$RC_FILE")"
    case "$RC_FILE" in
      */config.fish)
        cat >> "$RC_FILE" <<EOF

# >>> edit-tui >>>
if not contains "$BIN_DIR" \$PATH
    set -gx PATH "$BIN_DIR" \$PATH
end
# <<< edit-tui <<<
EOF
        ;;
      *)
        cat >> "$RC_FILE" <<EOF

# >>> edit-tui >>>
case ":\$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) PATH="$BIN_DIR:\$PATH" ;;
esac
export PATH
# <<< edit-tui <<<
EOF
        ;;
    esac
    RC_BLOCK=1
    say "已写入；新开终端或 source $RC_FILE 后生效"
  fi
fi

# ── 5. manifest ──────────────────────────────────────────────
say "写安装记录: $MANIFEST"
if [ "$DRY_RUN" != 1 ]; then
  mkdir -p "$STATE_DIR"
  {
    printf 'FORMAT=%q\n' 1
    printf 'MODE=%q\n' "$MODE"
    printf 'REPO=%q\n' "$REPO"
    printf 'BIN_DIR=%q\n' "$BIN_DIR"
    printf 'LAUNCHER=%q\n' "$LAUNCHER"
    printf 'RACKET=%q\n' "$RACKET_BIN"
    printf 'RC_FILE=%q\n' "$RC_FILE"
    printf 'RC_BLOCK=%q\n' "$RC_BLOCK"
  } > "$MANIFEST"
fi

say ""
say "完成。新终端里运行: $LAUNCHER_NAME"
if [ "$DRY_RUN" = 1 ]; then
  say "（dry-run，未做任何修改）"
fi
