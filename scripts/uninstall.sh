#!/usr/bin/env bash
# edit-tui 卸载脚本
#
# 默认只移除“程序”：rapper、PATH 块、Racket 包。
# 用户数据（配置 / 会话 / 缓存）默认保留；--purge 才删除。
# 永远不删除任何 <workspace>/.editdata。
#
# 用法：
#   scripts/uninstall.sh             # 移除程序
#   scripts/uninstall.sh --purge     # 同时删除配置 / 状态 / 缓存
#   scripts/uninstall.sh --dry-run
#   scripts/uninstall.sh --yes       # --purge 时不需要确认
#   scripts/uninstall.sh --manifest FILE

set -euo pipefail

MANIFEST="${XDG_STATE_HOME:-$HOME/.local/state}/edit/install.conf"
DRY_RUN=0
PURGE=0
YES=0
PKG=edit

usage() {
  sed -n '2,14p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [ $# -gt 0 ]; do
  case "$1" in
    --purge)    PURGE=1 ;;
    --yes|-y)   YES=1 ;;
    --dry-run)  DRY_RUN=1 ;;
    --manifest) MANIFEST="$2"; shift ;;
    -h|--help)  usage 0 ;;
    *) echo "未知参数: $1" >&2; usage 1 ;;
  esac
  shift
done

say() { printf '%s\n' "$*"; }
run() {
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    echo
  else
    "$@"
  fi
}

if [ ! -f "$MANIFEST" ]; then
  echo "找不到安装记录: $MANIFEST" >&2
  echo "如果包还在，可以手动执行: raco pkg remove $PKG" >&2
  exit 1
fi

# shellcheck disable=SC1090
. "$MANIFEST"
LAUNCHER="${LAUNCHER:-}"
BIN_DIR="${BIN_DIR:-${XDG_BIN_HOME:-$HOME/.local/bin}}"
RC_FILE="${RC_FILE:-}"
RC_BLOCK="${RC_BLOCK:-0}"

# ── 1. wrapper ───────────────────────────────────────────────
if [ -n "$LAUNCHER" ] && { [ -e "$LAUNCHER" ] || [ -L "$LAUNCHER" ]; }; then
  if head -n 3 "$LAUNCHER" 2>/dev/null | grep -qF '# generated by edit-tui install.sh'; then
    say "删除 wrapper: $LAUNCHER"
    run rm -f "$LAUNCHER"
  elif [ -L "$LAUNCHER" ]; then
    say "跳过非本脚本的符号链接: $LAUNCHER"
  else
    say "跳过非本脚本生成的文件: $LAUNCHER"
  fi
fi

# ── 2. PATH 块 ───────────────────────────────────────────────
if [ "$RC_BLOCK" = 1 ] && [ -n "$RC_FILE" ] && [ -f "$RC_FILE" ]; then
  say "从 $RC_FILE 移除 edit-tui PATH 块"
  if [ "$DRY_RUN" != 1 ]; then
    tmp="$(mktemp)"
    awk '
      $0 == "# >>> edit-tui >>>" { skip = 1; next }
      $0 == "# <<< edit-tui <<<" { skip = 0; next }
      !skip
    ' "$RC_FILE" > "$tmp"
    cat "$tmp" > "$RC_FILE"
    rm -f "$tmp"
  fi
fi

# ── 3. Racket 包 ─────────────────────────────────────────────
pkg_installed() {
  raco pkg show --dir "$PKG" 2>/dev/null \
    | awk -v p="$PKG" '$1 == p { found = 1 } END { exit !found }'
}

if command -v raco >/dev/null && pkg_installed; then
  say "移除 Racket 包: $PKG"
  # --no-setup：避免移除过程中被其它失效 link 挡住；需要时手动 raco setup
  run raco pkg remove --no-setup "$PKG"
fi

# ── 4. 用户数据 ──────────────────────────────────────────────
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/edit"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/edit"
CACHE_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/edit"
DATA_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/edit"

if [ "$PURGE" = 1 ]; then
  say ""
  say "--purge 将删除以下用户数据（不会碰任何 workspace/.editdata）："
  for d in "$CONFIG_DIR" "$STATE_DIR" "$CACHE_DIR" "$DATA_DIR"; do
    [ -e "$d" ] && say "  $d"
  done
  if [ "$YES" != 1 ]; then
    printf '确认删除? [y/N] '
    read -r ans
    case "$ans" in
      y|Y|yes|YES) ;;
      *) say "已取消删除用户数据"; PURGE=0 ;;
    esac
  fi
fi

if [ "$PURGE" = 1 ]; then
  for d in "$CONFIG_DIR" "$STATE_DIR" "$CACHE_DIR" "$DATA_DIR"; do
    if [ -e "$d" ]; then
      say "删除 $d"
      run rm -rf "$d"
    fi
  done
else
  say ""
  say "用户数据已保留："
  for d in "$CONFIG_DIR" "$STATE_DIR" "$CACHE_DIR"; do
    [ -e "$d" ] && say "  $d"
  done
  say "（需要一起删除时重跑: scripts/uninstall.sh --purge）"
fi

# ── 5. manifest ──────────────────────────────────────────────
if [ "$DRY_RUN" != 1 ]; then
  rm -f "$MANIFEST"
  rmdir "$(dirname "$MANIFEST")" 2>/dev/null || true
fi

say "卸载完成。"
if [ "$PURGE" != 1 ]; then
  say "注意：已打开终端里的 PATH 可能仍指向 $BIN_DIR，重开终端即可。"
fi
